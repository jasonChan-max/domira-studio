import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {CARE_LAYOUT_FEATURES,careLayoutFeatures} from '../public/care-layout-features.js';
import {planCareNightAccess} from '../public/care-home-planner.js';
import {trainingFamilies,makeTrainingCase} from './care-layout-training-cases.mjs';

const scale=[1,1,1,2,1];
const dot=(a,b)=>a.reduce((sum,value,index)=>sum+value*b[index],0);
const profiles=['walker','wheelchair'];
// Synthetic ground truth varies by brief. It favours short routes and limits needless rearrangement.
const reference={walker:[1,.30,.27,.15,.12],wheelchair:[1,.50,.15,.07,.08]};
const groups=[];
for(const family of trainingFamilies)for(const [index,variation] of family.variations.entries())for(const profile of profiles){
 const whole=makeTrainingCase(family,variation,profile);
 if(!whole)continue;
 const candidates=[];
 await planCareNightAccess(whole,{profile,rank:false,onCandidate(candidate){
  if(candidate.route.status!=='route-found')return;
  const features=careLayoutFeatures(whole,candidate).map((value,i)=>Number((value/scale[i]).toFixed(6)));
  if(candidates.some(row=>JSON.stringify(row.features)===JSON.stringify(features)))return;
  candidates.push({features,reference:Number(dot(reference[profile],features).toFixed(6))});
 }});
 if(candidates.length>1)groups.push({family:family.id,split:family.split,source:family.source,caseId:`${family.id}-${index+1}-${profile}`,profile,candidates});
}

function pairs(groups){
 return groups.flatMap(group=>group.candidates.flatMap((a,i)=>group.candidates.slice(i+1).flatMap(b=>{
  if(Math.abs(a.reference-b.reference)<.02)return [];
  const [better,worse]=a.reference<b.reference?[a,b]:[b,a];
  return [better.features.map((feature,k)=>worse.features[k]-feature)];
 })));
}
function train(rows){
 const weights=Array(CARE_LAYOUT_FEATURES.length).fill(.1);
 for(let epoch=0;epoch<600;epoch++){
  const gradient=weights.map(value=>value*.012);
  for(const row of rows){
   const update=-1/(1+Math.exp(Math.max(-50,Math.min(50,dot(weights,row)))));
   row.forEach((feature,i)=>{gradient[i]+=update*feature/rows.length;});
  }
  for(const [index,value] of gradient.entries())weights[index]=Math.max(0,weights[index]-.15*value);
 }
 return weights.map(value=>Number(value.toFixed(6)));
}
function evaluate(groups,weights){
 const comparisons=pairs(groups);
 const correct=comparisons.filter(row=>dot(row,weights)>1e-8).length;
 const meanRegret=groups.reduce((sum,group)=>{
  const winner=group.candidates.reduce((best,row)=>dot(row.features,weights)<dot(best.features,weights)?row:best);
  return sum+winner.reference-Math.min(...group.candidates.map(row=>row.reference));
 },0)/groups.length;
 return {groups:groups.length,pairs:comparisons.length,pairAccuracy:Number((correct/comparisons.length).toFixed(4)),meanRegret:Number(meanRegret.toFixed(4))};
}
const results={};
for(const profile of profiles){
 const trainGroups=groups.filter(group=>group.split==='train'&&group.profile===profile);
 const testGroups=groups.filter(group=>group.split==='test'&&group.profile===profile);
 const trainPairs=pairs(trainGroups);
 if(trainGroups.length<2||!trainPairs.length||testGroups.length<2||!pairs(testGroups).length)throw Error(`Insufficient independent cases for ${profile}`);
 const weights=train(trainPairs);
 results[profile]={weights,train:evaluate(trainGroups,weights),test:evaluate(testGroups,weights),baseline:evaluate(testGroups,[1,0,0,0,0])};
}
const model={version:1,labelBasis:'synthetic-preferences-v1',features:CARE_LAYOUT_FEATURES,scale,corpusSha256:createHash('sha256').update(JSON.stringify(groups)).digest('hex'),results};
const target=new URL('../public/care-layout-model.js',import.meta.url);
const output=`// Generated by scripts/train-care-layout.mjs --write\nexport const CARE_LAYOUT_MODEL = ${JSON.stringify(model,null,2)};\n`;
if(process.argv.includes('--write'))await writeFile(target,output);
if(process.argv.includes('--check')&&await readFile(target,'utf8')!==output)throw Error('Care layout model differs from the reproducible training run.');
console.log(JSON.stringify({model,corpus:groups.map(({caseId,source,split,candidates})=>({caseId,source,split,candidates:candidates.length}))},null,2));
